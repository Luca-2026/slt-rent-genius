#!/usr/bin/env node
// Sprint 6 – Aufgabe 2: .htaccess-Generator
// ---------------------------------------------------------------
// Liest scripts/.cache/404-mapping.json und schreibt eine komplette
// Production-.htaccess nach dist/.htaccess.
//
// Annahmen:
//   - Apache 2.4 / LiteSpeed-kompatibel
//   - Build-Time-Prerender hat bereits index.html-Files je Route abgelegt
//   - Bot-User-Agent-Routing ist NICHT mehr nötig (PHP-Prerender weg)
// ---------------------------------------------------------------

import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const MAPPING_PATH = resolve(process.cwd(), "scripts/.cache/404-mapping.json");
const DIST_DIR = resolve(process.cwd(), "dist");
const OUT_PATH = resolve(DIST_DIR, ".htaccess");

if (!existsSync(MAPPING_PATH)) {
  console.error(`[build-htaccess] FEHLT: ${MAPPING_PATH}\n   Zuerst: node scripts/audit-404-mapping.mjs`);
  process.exit(1);
}
if (!existsSync(DIST_DIR)) mkdirSync(DIST_DIR, { recursive: true });

const mapping = JSON.parse(readFileSync(MAPPING_PATH, "utf-8"));

// Escape special regex chars in source-paths so RewriteRule treats sie als
// Literale (Kolons in `Tarife:1` etc. müssen als Literal bleiben).
function escapeRe(s) {
  return s.replace(/[.+?^${}()|[\]\\]/g, "\\$&");
}

// Sortiere: spezifischere zuerst, generische zuletzt.
// Innerhalb gleicher Confidence: längere from-URL zuerst (verhindert
// dass `/produkte/foo` einen `/produkte/foo-bar`-Match überholt).
const concrete = mapping.mappings
  .filter((m) => m.method !== "fallback")
  .sort((a, b) => b.confidence - a.confidence || b.from.length - a.from.length);

const fallbacks = mapping.mappings.filter((m) => m.method === "fallback");

const lines = [];
lines.push(
  "# === SLT Rental — Production .htaccess ===",
  "# Generated by scripts/build-htaccess.mjs (Sprint 6)",
  `# Generated at: ${new Date().toISOString()}`,
  `# 404-Mapping source: scripts/.cache/404-mapping.json (${mapping.total} URLs)`,
  "",
  "Options -Indexes",
  "RewriteEngine On",
  "",
  "# === 1. HTTPS-Erzwingung ===",
  "# Alle HTTP-Anfragen → HTTPS, mit Erhalt von Pfad und Query-String",
  "RewriteCond %{HTTPS} !=on",
  "RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]",
  "",
  "# === 2. WWW-Erzwingung ===",
  "# Alle non-www → www (für NAP-Konsistenz)",
  "RewriteCond %{HTTP_HOST} ^slt-rental\\.de$ [NC]",
  "RewriteRule ^ https://www.slt-rental.de%{REQUEST_URI} [L,R=301]",
  "",
  "# === 3. Trailing-Slash-Konsistenz ===",
  "# Trailing slashes werden entfernt (außer für echte Verzeichnisse)",
  "RewriteCond %{REQUEST_FILENAME} !-d",
  "RewriteRule ^(.+)/$ /$1 [L,R=301]",
  "",
  `# === 4. Legacy-URL-Redirects (aus GSC-404-Liste, ${mapping.total} URLs) ===`,
  "# Generiert aus 404-mapping.json — sortiert nach Confidence absteigend.",
  "# Confidence:",
);
for (const [k, v] of Object.entries(mapping.byConfidence)) {
  lines.push(`#   ${k.padEnd(28)} ${v}`);
}
lines.push("");

// Konkrete Mappings nach Confidence-Buckets gruppieren
const buckets = [
  { label: "Direct/High-Confidence (>= 0.7)", filter: (m) => m.confidence >= 0.7 },
  { label: "Medium (0.5 - 0.69)", filter: (m) => m.confidence >= 0.5 && m.confidence < 0.7 },
  { label: "Low/Fuzzy (0.3 - 0.49) — manuell reviewed", filter: (m) => m.confidence >= 0.3 && m.confidence < 0.5 },
  { label: "Sehr niedrig (< 0.3) — Sicherheitsnetz", filter: (m) => m.confidence > 0 && m.confidence < 0.3 },
];

const seen = new Set();
for (const b of buckets) {
  const items = concrete.filter(b.filter);
  if (!items.length) continue;
  lines.push(`# --- ${b.label} (${items.length}) ---`);
  for (const m of items) {
    const fromPath = m.from.replace(/^\//, "");
    const sig = `${fromPath}|${m.to}`;
    if (seen.has(sig)) continue;
    seen.add(sig);
    const note = m.note ? `   # ${m.note}` : "";
    lines.push(`RewriteRule ^${escapeRe(fromPath)}$ ${m.to} [L,R=301]${note}`);
  }
  lines.push("");
}

if (fallbacks.length) {
  lines.push(`# --- Pauschal-Fallbacks (${fallbacks.length}, Confidence < 0.3) ---`);
  for (const m of fallbacks) {
    const fromPath = m.from.replace(/^\//, "");
    lines.push(`RewriteRule ^${escapeRe(fromPath)}$ ${m.to} [L,R=301]`);
  }
  lines.push("");
}

lines.push(
  "# === 5. Pauschale Legacy-Pattern-Fallbacks ===",
  "# Für alle nicht in der GSC-Liste enthaltenen Legacy-URLs: in den Standort-Hub.",
  "RewriteRule ^produkte/(.+)$ /mieten/krefeld [L,R=301]",
  "RewriteRule ^produkte-bonn/(.+)$ /mieten/bonn [L,R=301]",
  "RewriteRule ^produkte-duisburg/(.+)$ /mieten/muelheim [L,R=301]",
  "RewriteRule ^produkte-muelheim/(.+)$ /mieten/muelheim [L,R=301]",
  "RewriteRule ^produkte$ /mieten [L,R=301]",
  "RewriteRule ^kategorien-krefeld/(.+)$ /mieten/krefeld [L,R=301]",
  "RewriteRule ^kategorien-bonn/(.+)$ /mieten/bonn [L,R=301]",
  "RewriteRule ^kategorien-muelheim/(.+)$ /mieten/muelheim [L,R=301]",
  "RewriteRule ^kategorien-duisburg/(.+)$ /mieten/muelheim [L,R=301]",
  "RewriteRule ^kategroien-duisburg/(.+)$ /mieten/muelheim [L,R=301]",
  "RewriteRule ^kategorien/(.+)$ /mieten/krefeld [L,R=301]",
  "RewriteRule ^kategorie/krefeld-(.+)$ /mieten/krefeld [L,R=301,NC]",
  "RewriteRule ^kategorie/bonn-(.+)$ /mieten/bonn [L,R=301,NC]",
  "RewriteRule ^kategorie/muelheim-(.+)$ /mieten/muelheim [L,R=301,NC]",
  "RewriteRule ^kategorie/(.+)$ /mieten/krefeld [L,R=301]",
  "RewriteRule ^standort-krefeld$ /standorte/krefeld [L,R=301]",
  "RewriteRule ^standort-bonn$ /standorte/bonn [L,R=301]",
  "RewriteRule ^standort-duisburg$ /standorte/muelheim [L,R=301]",
  "RewriteRule ^standort-muelheim$ /standorte/muelheim [L,R=301]",
  "RewriteRule ^standort/krefeld$ /mieten/krefeld [L,R=301]",
  "RewriteRule ^standort/bonn$ /mieten/bonn [L,R=301]",
  "RewriteRule ^standort/muelheim$ /mieten/muelheim [L,R=301]",
  "RewriteRule ^standort/muehlheim$ /mieten/muelheim [L,R=301]",
  "RewriteRule ^wissensbasis$ /hilfe [L,R=301]",
  "RewriteRule ^loesungen/hochbau$ /loesungen/hochbau-renovierung [L,R=301]",
  "RewriteRule ^loesungen/tiefbau$ /loesungen/tiefbau-erdbewegung [L,R=301]",
  "RewriteRule ^loesungen/galabau$ /loesungen/garten-landschaftsbau [L,R=301]",
  "RewriteRule ^loesungen/events$ /loesungen/events-veranstaltungen [L,R=301]",
  "RewriteRule ^loesungen/handwerk$ /loesungen/handwerk-gewerbe [L,R=301]",
  "RewriteRule ^loesungen/transport$ /loesungen/umzug-transport [L,R=301]",
  "RewriteRule ^loesungen/kinder$ /loesungen/kindergeburtstage [L,R=301]",
  "",
  "# === 6. SPA-Fallback / Prerender ===",
  "# Prerendered Routes liegen als /pfad/index.html im Build – Apache",
  "# liefert das automatisch via DirectoryIndex aus.",
  "DirectoryIndex index.html",
  "",
  "RewriteCond %{REQUEST_FILENAME} !-f",
  "RewriteCond %{REQUEST_FILENAME} !-d",
  "RewriteRule ^ /index.html [L]",
  "",
  "# === 7. Cache-Header ===",
  "<IfModule mod_expires.c>",
  "  ExpiresActive On",
  "",
  "  # Bilder: 1 Jahr (vite-hashed Filenames)",
  "  ExpiresByType image/jpeg \"access plus 1 year\"",
  "  ExpiresByType image/png \"access plus 1 year\"",
  "  ExpiresByType image/webp \"access plus 1 year\"",
  "  ExpiresByType image/avif \"access plus 1 year\"",
  "  ExpiresByType image/svg+xml \"access plus 1 year\"",
  "  ExpiresByType image/x-icon \"access plus 1 year\"",
  "",
  "  # Fonts: 1 Jahr",
  "  ExpiresByType font/woff \"access plus 1 year\"",
  "  ExpiresByType font/woff2 \"access plus 1 year\"",
  "  ExpiresByType application/font-woff \"access plus 1 year\"",
  "  ExpiresByType application/font-woff2 \"access plus 1 year\"",
  "",
  "  # JS/CSS: 1 Jahr (vite-hashed Filenames)",
  "  ExpiresByType application/javascript \"access plus 1 year\"",
  "  ExpiresByType text/css \"access plus 1 year\"",
  "",
  "  # HTML: 1 Stunde (Prerender-Output kann sich ändern)",
  "  ExpiresByType text/html \"access plus 1 hour\"",
  "",
  "  # PDFs (Manuals): 1 Monat",
  "  ExpiresByType application/pdf \"access plus 1 month\"",
  "</IfModule>",
  "",
  "# === 8. Compression ===",
  "<IfModule mod_deflate.c>",
  "  AddOutputFilterByType DEFLATE text/html text/plain text/xml text/css",
  "  AddOutputFilterByType DEFLATE application/javascript application/json",
  "  AddOutputFilterByType DEFLATE image/svg+xml font/woff font/woff2",
  "</IfModule>",
  "",
  "# === 9. Security Headers ===",
  "<IfModule mod_headers.c>",
  "  Header set X-Content-Type-Options \"nosniff\"",
  "  Header set X-Frame-Options \"SAMEORIGIN\"",
  "  Header set Referrer-Policy \"strict-origin-when-cross-origin\"",
  "",
  "  # PDFs: noindex (Manuals sollen nicht in Google-Index)",
  "  <FilesMatch \"\\.pdf$\">",
  "    Header set X-Robots-Tag \"noindex, nofollow\"",
  "  </FilesMatch>",
  "</IfModule>",
  "",
  "# === 10. MIME-Types ===",
  "<IfModule mod_mime.c>",
  "  AddType image/avif .avif",
  "  AddType image/webp .webp",
  "  AddType font/woff2 .woff2",
  "</IfModule>",
  "",
  "AddDefaultCharset UTF-8",
  "",
  "# === 11. Custom Error Pages ===",
  "ErrorDocument 404 /index.html",
  "",
);

writeFileSync(OUT_PATH, lines.join("\n"), "utf-8");

const r301Count = lines.filter((l) => l.includes("R=301")).length;
console.log(`[build-htaccess] Wrote ${OUT_PATH}`);
console.log(`[build-htaccess]   ${lines.length} Zeilen, ${r301Count} 301-Redirects`);
console.log(`[build-htaccess]   ${concrete.length} konkrete + ${fallbacks.length} Fallback + ~30 pauschale Pattern-Redirects`);
